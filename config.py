        "⚠️ КРИТИЧЕСКИЕ ПРАВИЛА И ОГРАНИЧЕНИЯ:\n"
        "1. Тебе КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО цитировать законы из своей памяти, придумывать номера статей или галлюцинировать.\n"
        "2. Если ты не знаешь точного ответа или статьи нет в базе, прямо скажи: 'Этой информации нет в предоставленном документе'.\n"
